// Header is the doc's first line: what wrote it and how to write it again. Nothing in the doc varies between runs
// (no date, no version), or the golden would fail every time.
const Header = "<!-- Generated by github.com/trick77/ship/kit/schemadoc, do not edit. Regenerate " + RegenerateWhere +
	": " + Regenerate + " -->"

// Render writes the schema doc. It fails when an entity has no Table: line or names a table or view s lacks, listing
// every such entity. A row read from a view names the view: it is listed under it.
func Render(s Schema, entities []Entity) ([]byte, error) {
	s = Schema{Tables: slices.Clone(s.Tables), Views: slices.Clone(s.Views)}
	s.sort()
	tables := s.Tables
	es := slices.Clone(entities)
	slices.SortFunc(es, func(a, b Entity) int {
		return cmp.Or(strings.Compare(a.Dir, b.Dir), strings.Compare(a.Package, b.Package), strings.Compare(a.Name, b.Name))
	})

	byTable := map[string][]Entity{}
	var bad []string
	for _, e := range es {
		switch {
		case e.Table == "":
			bad = append(bad, e.QualifiedName()+": no Table: line in its doc comment (a table or view name, or - for none)")
		case e.Table != NoTable && s.table(e.Table) == nil && !s.hasView(e.Table):
			bad = append(bad, e.QualifiedName()+": no table or view "+e.Table)
		default:
			byTable[e.Table] = append(byTable[e.Table], e)
		}
	}
	if len(bad) > 0 {
		return nil, errors.New("schemadoc: " + strings.Join(bad, "; "))
	}

	var b bytes.Buffer
	b.WriteString(Header + "\n\n# Database schema\n\n")
	fmt.Fprintf(&b, "%s; the diagram is at the end. Go types are the `model.go` structs whose rows they hold.\n",
		strings.Join(append([]string{plural(len(tables), "table")}, viewCounts(s.Views)...), ", "))
	for _, t := range tables {
		writeTable(&b, t, byTable[t.Name])
	}
	if len(s.Views) > 0 {
		b.WriteString("\n## Views\n\n")
		for _, v := range s.Views {
			fmt.Fprintf(&b, "- %s (%s)\n", code(v.Name), v.Kind)
			for _, e := range byTable[v.Name] {
				b.WriteString("  ")
				writeEntityLine(&b, e)
			}
		}
	}
	if free := byTable[NoTable]; len(free) > 0 {
		b.WriteString("\n## Types not stored as rows\n")
		for _, e := range free {
			writeFreeEntity(&b, e)
		}
	}
	writeMermaid(&b, tables)
	return b.Bytes(), nil
}

func writeTable(b *bytes.Buffer, t Table, es []Entity) {
	fmt.Fprintf(b, "\n## %s\n\n", t.Name)
	if t.Module != "" {
		fmt.Fprintf(b, "Virtual table: %s.\n\n", code(t.Module+"("+t.ModuleArgs+")"))
	}
	if len(es) > 0 {
		b.WriteString("Go types:\n\n")
		for _, e := range es {
			writeEntityLine(b, e)
		}
		b.WriteString("\n")
	}
	b.WriteString("| Column | Type | Null | Default | PK |\n| --- | --- | --- | --- | --- |\n")
	for _, c := range t.Columns {
		def, pk := "", ""
		if c.HasDefault {
			def = code(c.Default)
		}
		if c.PK > 0 {
			pk = strconv.Itoa(c.PK)
		}
		fmt.Fprintf(b, "| %s | %s | %s | %s | %s |\n", code(c.Name), cell(c.Type), yesNo(!c.NotNull), def, pk)
	}
	if len(t.ForeignKeys) > 0 {
		b.WriteString("\nForeign keys:\n\n")
		for _, fk := range t.ForeignKeys {
			fmt.Fprintf(b, "- %s → %s (%s)%s\n", codeList(fk.Columns), code(fk.RefTable), codeList(fk.RefColumns), actions(fk))
		}
	}
	if len(t.Indexes) > 0 {
		b.WriteString("\nIndexes:\n\n")
		for _, i := range t.Indexes {
			fmt.Fprintf(b, "- %s (%s)", code(i.Name), codeList(i.Columns))
			if i.Unique {
				b.WriteString(" unique")
			}
			if i.Where != "" {
				fmt.Fprintf(b, " where %s", code(i.Where))
			}
			b.WriteString("\n")
		}
	}
	if len(t.Checks) > 0 {
		b.WriteString("\nChecks:\n\n")
		for _, c := range t.Checks {
			fmt.Fprintf(b, "- %s\n", code(c))
		}
	}
}

func writeEntityLine(b *bytes.Buffer, e Entity) {
	fmt.Fprintf(b, "- %s (%s)", code(e.QualifiedName()), e.Dir)
	if s := e.Summary(); s != "" {
		b.WriteString(": " + s)
	}
	b.WriteString("\n")
}

func writeFreeEntity(b *bytes.Buffer, e Entity) {
	fmt.Fprintf(b, "\n### %s\n\n", e.QualifiedName())
	fmt.Fprintf(b, "In %s.", code(e.Dir))
	if s := e.Summary(); s != "" {
		b.WriteString(" " + s)
	}
	b.WriteString("\n")
	if len(e.Fields) == 0 {
		return
	}
	b.WriteString("\n| Field | Type | Doc |\n| --- | --- | --- |\n")
	for _, f := range e.Fields {
		name := code(f.Name)
		if f.Embedded {
			name += " (embedded)"
		}
		fmt.Fprintf(b, "| %s | %s | %s |\n", name, code(f.Type), fieldDoc(f))
	}
}

// fieldDoc is a field's doc for its table cell: its paragraphs on one line each, split by <br> (a later paragraph
// may lean on the break); a field under another's doc comment, with none of its own, points to that field.
func fieldDoc(f Field) string {
	if f.Doc == "" && f.SharedDoc != "" {
		return "see " + code(f.SharedDoc)
	}
	// Entities wrote each paragraph on one line. The <br> makes the cell HTML: a < or & of the doc's own is escaped,
	// outside a code span (which shows its text as is).
	paras := strings.Split(f.Doc, "\n\n")
	for i, p := range paras {
		paras[i] = cell(htmlText(p))
	}
	return strings.Join(paras, "<br>")
}

// htmlText is s with <, > and & escaped outside `code spans`, for a cell holding HTML.
func htmlText(s string) string {
	var b strings.Builder
	code := false
	for _, r := range s {
		switch {
		case r == '`':
			code = !code
			b.WriteRune(r)
		case code:
			b.WriteRune(r)
		case r == '<':
			b.WriteString("&lt;")
		case r == '>':
			b.WriteString("&gt;")
		case r == '&':
			b.WriteString("&amp;")
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}

// actions is an FK's non-default referential actions.
func actions(fk ForeignKey) string {
	var out string
	if fk.OnDelete != "" && fk.OnDelete != "NO ACTION" {
		out += ", on delete " + fk.OnDelete
	}
	if fk.OnUpdate != "" && fk.OnUpdate != "NO ACTION" {
		out += ", on update " + fk.OnUpdate
	}
	return out
}

func writeMermaid(b *bytes.Buffer, tables []Table) {
	b.WriteString("\n## Diagram\n\n```mermaid\nerDiagram\n")
	for _, t := range tables {
		fkCols := map[string]bool{}
		for _, fk := range t.ForeignKeys {
			for _, c := range fk.Columns {
				fkCols[c] = true
			}
		}
		fmt.Fprintf(b, "    %s {\n", mermaidIdent(t.Name))
		for _, c := range t.Columns {
			var keys []string
			if c.PK > 0 {
				keys = append(keys, "PK")
			}
			if fkCols[c.Name] {
				keys = append(keys, "FK")
			}
			line := mermaidType(c.Type) + " " + mermaidIdent(c.Name)
			if len(keys) > 0 {
				line += " " + strings.Join(keys, ", ")
			}
			fmt.Fprintf(b, "        %s\n", line)
		}
		b.WriteString("    }\n")
	}
	for _, t := range tables {
		notNull := map[string]bool{}
		for _, c := range t.Columns {
			notNull[c.Name] = c.NotNull
		}
		for _, fk := range t.ForeignKeys {
			// A child row always has a parent when every key column is NOT NULL, else at most one.
			parent := "||"
			for _, c := range fk.Columns {
				if !notNull[c] {
					parent = "o|"
				}
			}
			// A parent has at most one child when the key columns are the child's primary key or a unique key.
			child := "}o"
			if t.oneToOne(fk.Columns) {
				child = "|o"
			}
			fmt.Fprintf(b, "    %s %s--%s %s : %q\n", mermaidIdent(t.Name), child, parent, mermaidIdent(fk.RefTable),
				strings.Join(fk.Columns, ", "))
		}
	}
	b.WriteString("```\n")
}

// mermaidIdent makes s a Mermaid erDiagram name: letters, digits and underscores, not starting with a digit.
func mermaidIdent(s string) string { return mermaidWord(s, identByte) }

// mermaidType makes s a Mermaid erDiagram attribute type. The grammar's attribute word (mermaid 9.4 on:
// [A-Za-z_][A-Za-z0-9\-_\[\]\(\)]*) also takes - [ ] ( ), so text[] and varchar(255) keep their spelling. Anything
// else becomes _: a space ends the word, and the comma and dot newer mermaid takes an older renderer rejects.
func mermaidType(s string) string {
	return mermaidWord(s, func(c byte) bool { return identByte(c) || strings.IndexByte("-[]()", c) >= 0 })
}

// mermaidWord is s with every byte keep rejects made _, prefixed with _ unless it starts with a letter or _; ANY
// when empty.
func mermaidWord(s string, keep func(byte) bool) string {
	if s == "" {
		return "ANY"
	}
	out := []byte(s)
	for i, c := range out {
		if !keep(c) {
			out[i] = '_'
		}
	}
	if c := out[0]; c != '_' && (c < 'a' || c > 'z') && (c < 'A' || c > 'Z') {
		return "_" + string(out)
	}
	return string(out)
}

func identByte(c byte) bool {
	return c == '_' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9'
}

// oneLine is s with its whitespace runs collapsed to single spaces, trimmed.
func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

// cell is s safe in a table cell: one line, pipes escaped.
func cell(s string) string {
	return strings.ReplaceAll(oneLine(s), "|", `\|`)
}

// code is s as inline code in a table cell. A backtick inside would end the span early, so the span is fenced with
// two then.
func code(s string) string {
	s = cell(s)
	if strings.Contains(s, "`") {
		return "`` " + s + " ``"
	}
	return "`" + s + "`"
}

func codeList(ss []string) string {
	out := make([]string, len(ss))
	for i, s := range ss {
		out[i] = code(s)
	}
	return strings.Join(out, ", ")
}

// viewKinds is the order viewCounts lists the known kinds in; any other kind follows, by name.
var viewKinds = []string{"view", "materialized view", "continuous aggregate"}

// viewCounts is the views counted per kind ("33 continuous aggregates"): calling TimescaleDB's aggregates views
// would hide what they are. A view without a kind counts as a view.
func viewCounts(views []View) []string {
	n := map[string]int{}
	var kinds []string
	for _, v := range views {
		k := cmp.Or(v.Kind, "view")
		if n[k] == 0 {
			kinds = append(kinds, k)
		}
		n[k]++
	}
	rank := func(k string) int {
		if i := slices.Index(viewKinds, k); i >= 0 {
			return i
		}
		return len(viewKinds)
	}
	slices.SortFunc(kinds, func(a, b string) int { return cmp.Or(cmp.Compare(rank(a), rank(b)), strings.Compare(a, b)) })
	var out []string
	for _, k := range kinds {
		out = append(out, plural(n[k], k))
	}
	return out
}

// plural is n and noun, an s appended unless n is 1.
func plural(n int, noun string) string {
	if n != 1 {
		noun += "s"
	}
	return strconv.Itoa(n) + " " + noun
}

func yesNo(v bool) string {
	if v {
		return "yes"
	}
	return "no"
}
