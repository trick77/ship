// ModelFile is the one file of a package that declares its row types.
const ModelFile = "model.go"

// tableLine is a row type's doc line naming its table or view; - when it maps no one table (an aggregate or
// DISTINCT). A join's row, its columns from more tables, names the table one value stands for.
var tableLine = regexp.MustCompile(`^Table: (?:[a-z0-9_]+|-)$`)

const modelWhy = "model.go declares the rows, the store scans them"

// dbImport: database/sql or pgx (github.com/jackc/pgx…, pgtype and pgxpool included), the imports that make a file
// store code.
func dbImport(p string) bool {
	return p == "database/sql" || strings.HasPrefix(p, "github.com/jackc/pgx")
}

// model: a row type, a named struct a row's Scan(…, dest ...any) fills a field of (see flow), lives in its package's
// model.go, its doc naming the table; model.go holds no database code. Only a module importing database/sql or pgx
// is loaded: one scanning solely through another module's interface is skipped, its schema checks too.
// Type-checked (go/packages), never matched by name: a scan target is the struct that declares the field, through a
// dest slice, an embedding or another package. Only go.dir's and
// go.modules' own types count, a function-local one is exempt (it cannot move without leaving its scope).
func (e *env) model() result {
	listed := e.listed()
	var mods []string
	for _, dir := range append([]string{e.c.Go.Dir}, e.c.Go.Modules...) {
		if dir = filepath.ToSlash(dir); e.importsDB(dir, listed) {
			mods = append(mods, dir)
		}
	}
	if len(mods) == 0 {
		return result{skip: "no database/sql or pgx import (no database)"}
	}
	var fs []finding
	for _, m := range mods {
		fs = append(fs, e.modelModule(m)...)
	}
	return result{findings: append(fs, e.schemaDoc(mods, listed)...)}
}

// SchemaDoc is the repo's generated schema, the tables and views the row types' Table lines name.
const SchemaDoc = "docs/schema.md"

// SchemaDocPrefix starts kit/schemadoc.Header, the generated file's first line. A copy: ship's root module does not
// import kit. Only the prefix: the rest (how to regenerate) changes between kit versions, and a consumer on an older
// kit still conforms.
const SchemaDocPrefix = "<!-- Generated by github.com/trick77/ship/kit/schemadoc, do not edit."

// SchemadocImport is the package whose Golden test keeps docs/schema.md current.
const SchemadocImport = "github.com/trick77/ship/kit/schemadoc"

// schemaDoc: a repo with a database has docs/schema.md as kit/schemadoc writes it, a test checking it (else it rots
// unseen) and AGENTS.md pointing at it.
func (e *env) schemaDoc(mods []string, listed map[string]bool) []finding {
	var fs []finding
	switch b, err := e.read(SchemaDoc); {
	case err != nil:
		fs = append(fs, finding{what: err.Error(), file: SchemaDoc})
	case b == nil:
		fs = append(fs, finding{what: "missing: generate it with kit/schemadoc (TestSchemaDoc)", file: SchemaDoc})
	default:
		// The comment closed on the first line too: an unclosed one hides the whole doc on GitHub.
		// A BOM or trailing whitespace an editor leaves renders the same: tolerated.
		first, _, _ := strings.Cut(strings.TrimPrefix(string(b), string(rune(0xFEFF))), "\n")
		if !strings.HasPrefix(first, SchemaDocPrefix) || !strings.HasSuffix(strings.TrimRight(first, " \t\r"), " -->") {
			fs = append(fs, finding{what: "not generated by kit/schemadoc (first line)", file: SchemaDoc})
		}
	}
	if !e.goldenTest(mods, listed) {
		fs = append(fs, finding{what: "no schemadoc.Golden call in a test: " + SchemaDoc + " goes stale unchecked " +
			"(TestSchemaDoc)", file: path.Join(mods[0], "go.mod")})
	}
	// AGENTS.md missing: agents reports it.
	if b, err := e.read("AGENTS.md"); err == nil && b != nil && !strings.Contains(string(b), SchemaDoc) {
		fs = append(fs, finding{what: "no " + SchemaDoc + " mention: the schema an agent reads first", file: "AGENTS.md"})
	}
	return fs
}

// goldenTest: a non-generated _test.go file of mods calls Golden on its import of kit/schemadoc.
func (e *env) goldenTest(mods []string, listed map[string]bool) bool {
	fset := token.NewFileSet()
	for f := range listed {
		if !strings.HasSuffix(f, "_test.go") || !slices.ContainsFunc(mods, func(m string) bool {
			return inModuleAt(m, f, listed)
		}) {
			continue
		}
		b, err := e.read(f)
		if err != nil || b == nil || !strings.Contains(string(b), SchemadocImport) {
			continue
		}
		af, err := parser.ParseFile(fset, f, b, parser.ParseComments|parser.SkipObjectResolution)
		if err != nil || ast.IsGenerated(af) {
			continue
		}
		name := ""
		for _, im := range af.Imports {
			if v, _ := strconv.Unquote(im.Path.Value); v == SchemadocImport {
				name = "schemadoc"
				if im.Name != nil {
					name = im.Name.Name
				}
			}
		}
		found := false
		ast.Inspect(af, func(n ast.Node) bool {
			if c, ok := n.(*ast.CallExpr); ok {
				if sel, ok := c.Fun.(*ast.SelectorExpr); ok && sel.Sel.Name == "Golden" {
					if id, ok := sel.X.(*ast.Ident); ok && id.Name == name {
						found = true
					}
				}
			}
			return !found
		})
		if found {
			return true
		}
	}
	return false
}

// importsDB: a non-test file of the module at dir imports database/sql or pgx. Imports only, no load: a module
// without a database is never type-checked.
func (e *env) importsDB(dir string, listed map[string]bool) bool {
	fset := token.NewFileSet()
	for f := range listed {
		if !strings.HasSuffix(f, ".go") || strings.HasSuffix(f, "_test.go") || !inModuleAt(dir, f, listed) {
			continue
		}
		b, err := e.read(f)
		if err != nil || b == nil {
			continue
		}
		af, err := parser.ParseFile(fset, f, b, parser.ImportsOnly)
		if err != nil {
			return true // the load names the error
		}
		for _, im := range af.Imports {
			if v, _ := strconv.Unquote(im.Path.Value); dbImport(v) {
				return true
			}
		}
	}
	return false
}

// rowType is a row type found in one module: where its first scan is, where it is declared, its doc.
type rowType struct {
	obj *types.TypeName
	at  token.Position
}

// modelModule loads the module at dir (./..., no tests) and checks its row types and model.go files. A package that
// does not load (go list, parse, compile) is one finding: the build fails on it too.
func (e *env) modelModule(dir string) []finding {
	gomod := path.Join(dir, "go.mod")
	if !e.exists(gomod) {
		return nil // reported by gomod
	}
	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax | packages.NeedTypes | packages.NeedTypesInfo,
		Dir:  filepath.Join(e.root, filepath.FromSlash(dir)),
	}
	pkgs, err := packages.Load(cfg, "./...")
	if err != nil {
		return []finding{{what: "cannot load: " + oneLine(err.Error()), file: gomod}}
	}
	var errs []string
	own := map[*types.Package]bool{}
	for _, p := range pkgs {
		for _, pe := range p.Errors {
			errs = append(errs, oneLine(pe.Error()))
		}
		own[p.Types] = true
	}
	if len(errs) > 0 {
		what := "cannot load: " + errs[0]
		if len(errs) > 1 {
			what += fmt.Sprintf(" (and %d more)", len(errs)-1)
		}
		return []finding{{what: what, file: gomod}}
	}
	slices.SortFunc(pkgs, func(a, b *packages.Package) int { return strings.Compare(a.PkgPath, b.PkgPath) })
	if len(pkgs) == 0 {
		return nil
	}
	var fs []finding
	docs := map[token.Pos]*ast.CommentGroup{}
	fl := newFlow(pkgs, own)
	for _, p := range pkgs {
		for _, af := range p.Syntax {
			f := e.rel(p.Fset.Position(af.Pos()).Filename)
			typeDocs(af, docs)
			if path.Base(f) != ModelFile {
				continue
			}
			for _, im := range af.Imports {
				if v, _ := strconv.Unquote(im.Path.Value); dbImport(v) {
					fs = append(fs, finding{what: "imports " + v + ": " + modelWhy, file: f})
				}
			}
			fs = append(fs, scanCalls(p.Fset, af, f, func(c *ast.CallExpr) bool {
				_, ok := fl.rowScan(p.TypesInfo, c)
				return ok
			})...)
		}
	}
	fset := pkgs[0].Fset // one load, one file set
	rows := map[*types.TypeName]token.Position{}
	for _, d := range fl.dests() {
		if obj := e.credit(d.info, d.sel, own); obj != nil {
			at := fset.Position(d.sel.Pos())
			at.Filename = e.rel(at.Filename)
			if prev, ok := rows[obj]; !ok || before(at, prev) {
				rows[obj] = at
			}
		}
	}
	return append(fs, e.rowFindings(fset, rows, docs)...)
}

// before orders positions by file, then line.
func before(a, b token.Position) bool {
	if a.Filename != b.Filename {
		return a.Filename < b.Filename
	}
	return a.Line < b.Line
}

// typeDocs records every package-level type's doc by its name's position. A lone type's doc hangs on its decl, a
// grouped one's on its spec.
func typeDocs(af *ast.File, docs map[token.Pos]*ast.CommentGroup) {
	for _, decl := range af.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}
		for _, s := range gd.Specs {
			ts := s.(*ast.TypeSpec)
			doc := ts.Doc
			if doc == nil && len(gd.Specs) == 1 {
				doc = gd.Doc
			}
			docs[ts.Name.Pos()] = doc
		}
	}
}

// scanCalls: model.go calling a row's Scan (rowScan): a bufio or fmt Scan reads no row.
func scanCalls(fset *token.FileSet, af *ast.File, f string, rowScan func(*ast.CallExpr) bool) []finding {
	var fs []finding
	ast.Inspect(af, func(n ast.Node) bool {
		if c, ok := n.(*ast.CallExpr); ok && rowScan(c) {
			fs = append(fs, finding{what: fmt.Sprintf("calls Scan (line %d): %s", fset.Position(c.Pos()).Line,
				modelWhy), file: f})
		}
		return true
	})
	return fs
}

// isAppend: c calls the builtin append on a []any.
func isAppend(info *types.Info, c *ast.CallExpr) bool {
	id, ok := ast.Unparen(c.Fun).(*ast.Ident)
	if !ok || len(c.Args) == 0 {
		return false
	}
	_, ok = info.Uses[id].(*types.Builtin)
	return ok && id.Name == "append" && anySlice(info.TypeOf(c.Args[0]))
}

// anySlice: a slice of the empty interface, a Scan's dest.
func anySlice(t types.Type) bool {
	if t == nil {
		return false
	}
	s, ok := t.Underlying().(*types.Slice)
	if !ok {
		return false
	}
	i, ok := s.Elem().Underlying().(*types.Interface)
	return ok && i.Empty()
}

// credit is the named struct declaring s's field (&x.y.F: y's type; a promoted field: the embedded struct), when
// one of own's packages declares it at package level. A field of an unnamed struct credits the field holding it.
func (e *env) credit(info *types.Info, s *ast.SelectorExpr, own map[*types.Package]bool) *types.TypeName {
	sel, ok := info.Selections[s]
	if !ok || sel.Kind() != types.FieldVal {
		return nil
	}
	t := sel.Recv()
	idx := sel.Index()
	for _, i := range idx[:len(idx)-1] {
		st, ok := deref(t).Underlying().(*types.Struct)
		if !ok {
			return nil
		}
		t = st.Field(i).Type()
	}
	n, ok := deref(t).(*types.Named)
	if !ok {
		if outer, ok := ast.Unparen(s.X).(*ast.SelectorExpr); ok {
			return e.credit(info, outer, own)
		}
		return nil
	}
	obj := n.Origin().Obj()
	if obj.Pkg() == nil || !own[obj.Pkg()] || obj.Parent() != obj.Pkg().Scope() {
		return nil
	}
	return obj
}

func deref(t types.Type) types.Type {
	t = types.Unalias(t)
	if p, ok := t.(*types.Pointer); ok {
		return types.Unalias(p.Elem())
	}
	return t
}

// rowFindings: each row type outside model.go or without its Table line, by file and name.
func (e *env) rowFindings(fset *token.FileSet, rows map[*types.TypeName]token.Position, docs map[token.Pos]*ast.CommentGroup) []finding {
	rs := make([]rowType, 0, len(rows))
	for obj, at := range rows {
		rs = append(rs, rowType{obj, at})
	}
	file := func(r rowType) string { return e.rel(fset.Position(r.obj.Pos()).Filename) }
	slices.SortFunc(rs, func(a, b rowType) int {
		if c := strings.Compare(file(a), file(b)); c != 0 {
			return c
		}
		return strings.Compare(a.obj.Name(), b.obj.Name())
	})
	var fs []finding
	for _, r := range rs {
		f, name := file(r), r.obj.Name()
		switch {
		case path.Base(f) != ModelFile:
			fs = append(fs, finding{what: fmt.Sprintf("%s is a row type (scanned at %s:%d), declare it in %s",
				name, r.at.Filename, r.at.Line, ModelFile), file: f})
		case !hasTableLine(docs[r.obj.Pos()]):
			fs = append(fs, finding{what: fmt.Sprintf("row type %s: no %q doc line (- when it maps no one table)",
				name, "Table: <name>"), file: f})
		}
	}
	return fs
}

func hasTableLine(doc *ast.CommentGroup) bool {
	if doc == nil {
		return false
	}
	for _, l := range strings.Split(doc.Text(), "\n") {
		if tableLine.MatchString(strings.TrimSpace(l)) {
			return true
		}
	}
	return false
}

// oneLine: the go tool's multi-line error on a conform line.
func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

// rel is an absolute path the go tool reports, repo-relative in slash form. The go tool may report the root
// through its symlinks resolved (macOS: /var is /private/var).
func (e *env) rel(abs string) string {
	roots := []string{e.root}
	if r, err := filepath.EvalSymlinks(e.root); err == nil {
		roots = append(roots, r)
	}
	for _, r := range roots {
		if rel, err := filepath.Rel(r, abs); err == nil && !strings.HasPrefix(rel, "..") {
			return filepath.ToSlash(rel)
		}
	}
	return filepath.ToSlash(abs)
}
